-- V116: 이미 있는 콘텐츠의 사본을 원본 업로드와 구분한다
--
-- ## 왜 필요한가
--
-- 요금제의 "월 업로드" 한도(Free 5 / Starter 30 / Pro 100)는 사용자가 **새로 들여온 원본**을
-- 세야 한다. 그런데 영상 행을 만드는 경로 대부분이 source 를 지정하지 않아 기본값 UPLOAD_PC
-- 로 남았고, 월 카운트는 source 와 상관없이 **모든 행**을 셌다.
--
--   - 쇼츠 파이프라인이 클립 20개를 만들면 그 20개가 "업로드" 로 세어진다
--     → 무료 사용자가 쇼츠를 한 번 돌리면 정작 자기 영상을 올리지 못한다
--   - 재활용·반복 예약은 이미 센 원본을 **복사**해 새 행을 만든다 → 같은 콘텐츠를 두 번 센다
--
-- 쇼츠 결과물은 기존 GENERATED 로 옮기고(크레딧으로 이미 과금됨), 사본에는 새 값 DERIVED 를
-- 쓴다. 월 카운트는 UPLOAD_PC·GOOGLE_DRIVE·URL_IMPORT 만 센다(MonthlyUploadPolicy).
--
-- ## 기존 행
--
-- 과거 행은 다시 분류하지 않는다. 어느 행이 쇼츠 클립·재활용 사본이었는지 source 만으로는
-- 알 수 없고, 추측해 바꾸면 사용자의 이번 달 남은 횟수를 근거 없이 바꾸게 된다. 월 카운트는
-- 이번 달 생성분만 보므로, 배포 이후 생성분부터 정확해지고 다음 달부터는 전부 정확하다.
--
-- PostgreSQL 12+ 는 트랜잭션 안의 ADD VALUE 를 허용한다(같은 트랜잭션에서 사용하지는 않는다).
ALTER TYPE video_source ADD VALUE IF NOT EXISTS 'DERIVED';
