-- 파이프라인 차감의 **출처 분해**를 남긴다.
--
-- ## 왜 필요한가
--
-- 크레딧 차감은 무료분을 먼저 쓰고 모자라면 구매 패키지를 만료 임박순으로 가져간다.
-- 그런데 파이프라인 정산(사용자 취소·자연 실패·재시작 뒤 복구 tick)은 차감이 일어난
-- 요청과 다른 요청에서 실행되므로, 그때 만든 인메모리 영수증을 가질 수 없었다.
--
-- 그래서 환불이 출처를 모른 채 전액을 무료분에 얹었다. 결과는 고객 자산의 손실이다.
--
--   * 구매분에서 나간 크레딧이 월말에 사라지는 무료분으로 바뀐다.
--   * free_monthly 한도에 걸린 몫은 어디에도 복구되지 않고 그대로 증발한다.
--
-- 분해를 여기 남기면 정산이 정확히 같은 패키지로 되돌릴 수 있다.
--
-- ## 형식
--
--   {"freeAmount": 2, "purchasedAmounts": {"11": 3, "12": 5}}
--
-- 키는 ai_purchased_credits.id 다. 만료일이 다른 패키지 사이에서 유효기간이 바뀌지
-- 않도록 패키지별로 남긴다.
--
-- ## 기존 행
--
-- NULL 을 허용한다. 이 마이그레이션 이전에 만들어진 파이프라인은 분해를 알 수 없다.
-- 그 행들은 **자동 환불하지 않고** 운영 수기 정산으로 넘긴다 — 출처를 모르는 채
-- 무료분으로 돌려주는 것이 바로 이 컬럼이 막으려는 손실이기 때문이다.
--
-- 기본값을 두지 않는 이유도 같다. '{}'::jsonb 같은 값을 넣으면 "분해가 없다"와
-- "분해가 비어 있다"가 구분되지 않아, 레거시 행이 정상 행처럼 보인다.
--
-- ## 안전성
--
-- nullable 컬럼 추가 한 건이며 기본값 채우기가 없다. PostgreSQL 11+ 에서 테이블 재작성
-- 없이 즉시 완료된다. 기존 읽기/쓰기 경로는 이 컬럼을 몰라도 그대로 동작한다.

ALTER TABLE ai_pipeline_jobs
    ADD COLUMN IF NOT EXISTS credit_allocation JSONB;

COMMENT ON COLUMN ai_pipeline_jobs.credit_allocation IS
    '차감 출처 분해 {"freeAmount":N,"purchasedAmounts":{"<ai_purchased_credits.id>":N}}. NULL 은 마이그레이션 이전 행이며 자동 환불 대상이 아니다';
